  datos.map(
    ([pregunta, correcta, distractor1, distractor2, distractor3], i) => {
      const opciones = [correcta, distractor1, distractor2, distractor3];
      const posicion = i % 4;
      opciones.push(...opciones.splice(0, posicion));
      return {
        nivel,
        tema: `unidad-${nivel}`,
        dificultad,
        pregunta,
        opciones,
        correcta: (4 - posicion) % 4,
      };
    },
  );

